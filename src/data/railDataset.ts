function makeOffer(
  travelClass: TravelClass,
  baseFare: number,
  demoSeatsLeft: number,
  coaches: string[]
): TrainClassOffer {
  const availabilityLabel =
    demoSeatsLeft > 12
      ? `AVL ${demoSeatsLeft} (Demo)`
      : demoSeatsLeft > 0
        ? `AVL ${demoSeatsLeft} Fast Filling`
        : 'RAC 04 (Demo)';
  return {
    travelClass,
    baseFare,
    demoSeatsLeft,
    availabilityLabel,
    coaches,
  };
}

